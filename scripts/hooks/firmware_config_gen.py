#!/usr/bin/env python3
"""
Generates firmware network headers from ShowControl/network.json.

Two ways to run it:

  * As a Claude Code hook — receives the tool-use JSON on stdin and exits
    immediately unless the edited file was network.json.
  * By hand — ``python3 scripts/hooks/firmware_config_gen.py`` regenerates
    everything unconditionally. Do this before flashing.

network.json is the single source of truth for every address on the Show
Network (AGENTS.md constraint #3). Firmware never hardcodes an IP or MAC; it
includes the header this script writes.

Generated:

  Firmware/TreeHouse_Controllers/include/net_config.h   (ADR-0020)
  Firmware/FlowerBeds_Follow_ServoController/config.h

Both are committed, so a checkout can be flashed without running this first.
scripts/test_firmware_config_gen.py fails if either is out of date.
"""
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
NETWORK_JSON = REPO_ROOT / "ShowControl" / "network.json"
TREEHOUSE_HEADER = (
    REPO_ROOT / "Firmware" / "TreeHouse_Controllers" / "include" / "net_config.h"
)

FLOWERBEDS_HEADER = (
    REPO_ROOT / "Firmware" / "FlowerBeds_Follow_ServoController" / "config.h"
)
# One OpenRB-150 per network.json entry named flowerbeds_controller_<N>.
FLOWERBEDS_KEY = re.compile(r"flowerbeds_controller_(\d+)")

GENERATED_BANNER = [
    "// Generated by scripts/hooks/firmware_config_gen.py from ShowControl/network.json.",
    "// Do not edit by hand — edit network.json and re-run the script.",
]

# Firmware key in network.json → CG_TARGET_* macro suffix used by platformio.ini.
TREEHOUSE_LOCATIONS = {
    "treehouse_swannatopia": "SWANNATOPIA",
    "treehouse_julia": "JULIA",
    "treehouse_jess": "JESS",
    "treehouse_dormer": "DORMER",
    "treehouse_garage": "GARAGE",
}


def _octets(name: str, dotted: str) -> str:
    parts = dotted.split(".")
    if len(parts) != 4 or not all(p.isdigit() and 0 <= int(p) <= 255 for p in parts):
        raise ValueError(f"{name}: {dotted!r} is not a dotted-quad IPv4 address")
    return ", ".join(parts)


def render_treehouse_header(network: dict) -> str:
    lan = network.get("lan", {})
    gateway = lan.get("gateway")
    netmask = lan.get("netmask")
    if not gateway or not netmask:
        raise ValueError("network.json needs a 'lan' block with 'gateway' and 'netmask'")

    firmware = network.get("firmware", {})
    missing = [k for k in TREEHOUSE_LOCATIONS if k not in firmware]
    if missing:
        raise ValueError(f"network.json is missing firmware entries: {', '.join(missing)}")

    lines = [
        *GENERATED_BANNER,
        "",
        "#pragma once",
        "",
        f"#define CG_LAN_GATEWAY {{ {_octets('lan.gateway', gateway)} }}",
        f"#define CG_LAN_NETMASK {{ {_octets('lan.netmask', netmask)} }}",
        "",
    ]

    for key, macro in TREEHOUSE_LOCATIONS.items():
        entry = firmware[key]
        ip = entry.get("ip")
        port = entry.get("osc_port")
        if not ip or not port:
            raise ValueError(f"network.json: firmware.{key} needs both 'ip' and 'osc_port'")
        lines += [
            f"// {key}",
            f"#define CG_IP_{macro} {{ {_octets(key + '.ip', ip)} }}",
            f"#define CG_IP_STR_{macro} \"{ip}\"",
            f"#define CG_OSC_PORT_{macro} {int(port)}",
            "",
        ]

    return "\n".join(lines)


def _mac_bytes(name: str, mac: str) -> str:
    parts = mac.split(":")
    if len(parts) != 6 or not all(re.fullmatch(r"[0-9A-Fa-f]{2}", p) for p in parts):
        raise ValueError(f"{name}: {mac!r} is not a MAC address like DE:AD:BE:EF:15:00")
    return ", ".join(f"0x{p.upper()}" for p in parts)


def render_flowerbeds_header(network: dict) -> str:
    """One #if branch per flowerbeds_controller_<N>, selected by FLOWERBEDS_BOARD."""
    boards = sorted(
        (int(m.group(1)), key, entry)
        for key, entry in network.get("firmware", {}).items()
        if (m := FLOWERBEDS_KEY.fullmatch(key))
    )
    if not boards:
        raise ValueError("network.json has no firmware.flowerbeds_controller_<N> entries")

    numbers = " or ".join(str(n) for n, _, _ in boards)
    lines = [
        *GENERATED_BANNER,
        "//",
        f"// The sketch defines FLOWERBEDS_BOARD ({numbers}) before including this file.",
        "// Board <N> is firmware.flowerbeds_controller_<N> in network.json.",
        "",
        "#pragma once",
        "",
    ]

    for i, (n, key, entry) in enumerate(boards):
        ip, mac, port = entry.get("ip"), entry.get("mac"), entry.get("osc_port")
        if not ip or not mac or not port:
            raise ValueError(f"network.json: firmware.{key} needs 'ip', 'mac' and 'osc_port'")
        lines += [
            f"#{'if' if i == 0 else 'elif'} FLOWERBEDS_BOARD == {n}",
            f"// {key}",
            f"#define CG_MAC {{ {_mac_bytes(key + '.mac', mac)} }}",
            f"#define CG_IP {_octets(key + '.ip', ip)}",
            f"#define CG_OSC_PORT {int(port)}",
        ]

    lines += [
        "#else",
        f'#error "Set FLOWERBEDS_BOARD to {numbers} in the sketch: which board is being flashed?"',
        "#endif",
        "",
    ]
    return "\n".join(lines)


# Header path → function rendering it from the parsed network.json.
HEADERS = {
    TREEHOUSE_HEADER: render_treehouse_header,
    FLOWERBEDS_HEADER: render_flowerbeds_header,
}


def generate() -> list[Path]:
    network = json.loads(NETWORK_JSON.read_text())
    for path, render in HEADERS.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render(network))
    return list(HEADERS)


def main() -> None:
    if not sys.stdin.isatty():
        raw = sys.stdin.read()
        if raw.strip():
            data = json.loads(raw)
            file_path = data.get("tool_input", {}).get("file_path", "")
            if "network.json" not in file_path:
                sys.exit(0)

    for path in generate():
        print(f"regenerated {path.relative_to(REPO_ROOT)}", file=sys.stderr)


if __name__ == "__main__":
    main()
